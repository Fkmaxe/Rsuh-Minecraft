"""Map catalogue stored in runtime/maps/<name>/ (map.json + optional saved world/).

A map without a saved world is generated by the Paper plugin from its "layout"
("classic" or "empty"). Saving a map from the editor stores its world and clears the layout.
"""
from __future__ import annotations

import copy
import json
import math
import random
import re
import shutil
from pathlib import Path

NAME = re.compile(r'[a-z0-9_-]{1,24}')
MODES = ('1v1', '2v2', '5v5')
SHOPS = ('blocs', 'armes', 'armures', 'equipement')
GENERATORS = ('bronze', 'fer', 'or')
FACINGS = ('north', 'south', 'east', 'west')
LAYOUTS = ('classic', 'empty')
SIDES = ('rouge', 'bleu')
# Only blocks and entities are part of a map. Player data must never travel with it (an editor's
# inventory and position would follow them into games) and level data is rebuilt by the plugin.
WORLD_PARTS = ('region', 'entities', 'poi')


def _classic():
    npcs, generators = [], []
    for side, base in enumerate((-32, 32)):
        for i, shop in enumerate(SHOPS):
            npcs.append({'x': base - 4.5 + i * 3, 'y': 65.0, 'z': 6.5, 'yaw': 180.0, 'shop': shop, 'side': side})
        generators += [{'x': base + 0.5, 'y': 65.5, 'z': 0.5, 'type': 'bronze'},
                       {'x': base + 2.5, 'y': 65.5, 'z': 0.5, 'type': 'fer'}]
    generators.append({'x': 0.5, 'y': 65.5, 'z': 0.5, 'type': 'or'})
    return {'name': 'classic', 'modes': list(MODES), 'enabled': True, 'layout': 'classic',
            'spawns': [[-31.5, 65.0, 3.5, -90.0, 0.0], [32.5, 65.0, 3.5, 90.0, 0.0]],
            'beds': [[-32, 65, -3, 'north'], [32, 65, -3, 'north']],
            'npcs': npcs, 'generators': generators,
            'build': {'min_y': 60, 'max_y': 110}, 'void_y': 40, 'border': {'x': 0.0, 'z': 0.0, 'size': 180.0}}


CLASSIC = _classic()


def empty(name):
    return {'name': name, 'modes': list(MODES), 'enabled': False, 'layout': 'empty', 'spawns': [None, None],
            'beds': [None, None], 'npcs': [], 'generators': [], 'build': {'min_y': 0, 'max_y': 200},
            'void_y': -10, 'border': {'x': 0.0, 'z': 0.0, 'size': 300.0}}


def problems(m):
    """Reasons why a map cannot be played (empty list = playable)."""
    issues = [f'spawn {SIDES[i]} manquant' for i in range(2) if not m['spawns'][i]]
    issues += [f'lit {SIDES[i]} manquant' for i in range(2) if not m['beds'][i]]
    if not any(g['type'] == 'bronze' for g in m['generators']):
        issues.append('aucun générateur de bronze')
    return issues


def _number(value, low=-30_000_000, high=30_000_000):
    if type(value) not in (int, float) or not math.isfinite(value) or not low <= value <= high:
        raise ValueError('Coordonnée invalide')
    return float(value)


def sanitize(name, data):
    """Validate a map sent by the editor plugin; only known fields survive."""
    if not isinstance(data, dict):
        raise ValueError('Map invalide')
    spawns = data.get('spawns')
    beds = data.get('beds')
    if not (isinstance(spawns, list) and isinstance(beds, list) and len(spawns) == 2 and len(beds) == 2):
        raise ValueError('Spawns ou lits invalides')
    out = {'name': name, 'layout': None,
           'spawns': [None if s is None else [_number(v) for v in s] if isinstance(s, list) and len(s) == 5 else None for s in spawns],
           'beds': [], 'npcs': [], 'generators': []}
    for bed in beds:
        if bed is None:
            out['beds'].append(None)
        elif isinstance(bed, list) and len(bed) == 4 and bed[3] in FACINGS:
            out['beds'].append([int(_number(v)) for v in bed[:3]] + [bed[3]])
        else:
            raise ValueError('Lit invalide')
    for npc in data.get('npcs', [])[:64]:
        if npc.get('shop') not in SHOPS or npc.get('side') not in (0, 1):
            raise ValueError('PNJ invalide')
        out['npcs'].append({k: _number(npc[k]) for k in ('x', 'y', 'z', 'yaw')} | {'shop': npc['shop'], 'side': npc['side']})
    for gen in data.get('generators', [])[:64]:
        if gen.get('type') not in GENERATORS:
            raise ValueError('Générateur invalide')
        out['generators'].append({k: _number(gen[k]) for k in ('x', 'y', 'z')} | {'type': gen['type']})
    build = data.get('build', {})
    out['build'] = {'min_y': int(_number(build.get('min_y'), -64, 320)), 'max_y': int(_number(build.get('max_y'), -64, 320))}
    if out['build']['min_y'] >= out['build']['max_y']:
        raise ValueError('Hauteurs de construction invalides')
    out['void_y'] = int(_number(data.get('void_y'), -128, 320))
    border = data.get('border', {})
    out['border'] = {'x': _number(border.get('x')), 'z': _number(border.get('z')), 'size': _number(border.get('size'), 16, 4000)}
    return out


def copy_world(src, dest):
    """Copy the map parts of a world (blocks, entities, points of interest) into dest."""
    src, dest = Path(src), Path(dest)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for part in WORLD_PARTS:
        if (src / part).is_dir():
            shutil.copytree(src / part, dest / part, symlinks=False)


class Maps:
    def __init__(self, folder):
        self.dir = Path(folder)
        self.dir.mkdir(parents=True, exist_ok=True)
        if not (self.dir / 'classic' / 'map.json').exists():
            self._write('classic', CLASSIC)

    def _path(self, name):
        if not isinstance(name, str) or not NAME.fullmatch(name):
            raise ValueError('Nom de map : 1 à 24 caractères a-z, 0-9, _ ou -')
        return self.dir / name

    def _write(self, name, data):
        folder = self._path(name)
        folder.mkdir(parents=True, exist_ok=True)
        temp = folder / 'map.json.tmp'
        temp.write_text(json.dumps(data, indent=2))
        temp.replace(folder / 'map.json')

    def names(self):
        return sorted(p.parent.name for p in self.dir.glob('*/map.json') if NAME.fullmatch(p.parent.name))

    def load(self, name):
        path = self._path(name) / 'map.json'
        if not path.exists():
            raise ValueError('Map inconnue : ' + name)
        return json.loads(path.read_text())

    def world(self, name):
        world = self._path(name) / 'world'
        return str(world) if (world / 'region').is_dir() else None

    def summary(self):
        rows = []
        for name in self.names():
            m = self.load(name)
            rows.append({'name': name, 'enabled': m['enabled'], 'modes': m['modes'], 'problems': problems(m),
                         'npcs': len(m['npcs']), 'generators': len(m['generators'])})
        return rows

    def create(self, name, template='classic'):
        if self._path(name).exists():
            raise ValueError('Une map porte déjà ce nom')
        if template == 'classic':
            data = copy.deepcopy(CLASSIC) | {'name': name, 'enabled': False}
        elif template in ('empty', 'vide'):
            data = empty(name)
        else:
            source = self._path(template)
            data = self.load(template) | {'name': name, 'enabled': False}
            if self.world(template):
                copy_world(source / 'world', self._path(name) / 'world')
        self._write(name, data)
        return data

    def delete(self, name):
        if name == 'classic':
            raise ValueError('La map classic sert de secours : la désactiver plutôt que la supprimer')
        self.load(name)
        shutil.rmtree(self._path(name))

    def set_enabled(self, name, enabled):
        m = self.load(name)
        if enabled and problems(m):
            raise ValueError('Map incomplète : ' + ', '.join(problems(m)))
        m['enabled'] = enabled
        self._write(name, m)

    def set_modes(self, name, modes):
        if not modes or any(mode not in MODES for mode in modes):
            raise ValueError('Modes : 1v1, 2v2, 5v5 (séparés par des virgules)')
        m = self.load(name)
        m['modes'] = [mode for mode in MODES if mode in modes]
        self._write(name, m)

    def choose(self, mode):
        """Random playable map for a mode; the built-in classic map is the fallback."""
        candidates = []
        for name in self.names():
            m = self.load(name)
            if m['enabled'] and mode in m['modes'] and not problems(m):
                candidates.append(m)
        m = random.choice(candidates) if candidates else copy.deepcopy(CLASSIC)
        return m, self.world(m['name']) if candidates else None

    def commit(self, name, data, staging):
        """Store the editor's map and saved world (staging/world, flushed by Paper)."""
        current = self.load(name)
        clean = sanitize(name, data) | {'modes': current['modes'], 'enabled': current['enabled'] and not problems(sanitize(name, data))}
        staging = Path(staging)
        folder = self._path(name)
        if (staging / 'region').is_dir():
            fresh, old = folder / 'world.new', folder / 'world.old'
            for path in (fresh, old):
                if path.exists():
                    shutil.rmtree(path)
            copy_world(staging, fresh)
            if (folder / 'world').exists():
                (folder / 'world').rename(old)
            fresh.rename(folder / 'world')
            if old.exists():
                shutil.rmtree(old)
        elif current.get('layout'):
            clean['layout'] = current['layout']  # Nothing saved yet: keep generating it.
        self._write(name, clean)
        return clean
